namespace CommCodeVerifier.Core;

/// <summary>Идентификаторы правил. Числовое значение = номер правила в ТЗ.</summary>
public enum RuleId
{
    DecimalSeparator = 1, // Замена «.» на «,» в размерах и единицах измерения
    TrimSpaces = 2, // Удаление пробелов в начале/конце (+ нормализация кратных)
    ControlChars = 3, // Удаление непечатаемых и служебных символов
    DimensionX = 4, // «х»/«x» -> латинская «x» в перечислениях размеров
    ThreadDesignation = 5, // «х»/«x» -> «X», «М»/«m» -> «M» в обозначениях резьбы
    Dashes = 6, // en dash / em dash -> «-»
    SignificantWords = 7, // Удаление значащих слов
    TrailingEnding = 8, // Удаление окончания
    ArticleExclusion = 9, // Комм. код удалён по виду артикула
    HomoglyphLetters = 10, // Замена кириллических букв на совпадающие по написанию латинские
    ArticleExtraction = 11, // Оставить в коде только артикул
    CatalogStartReview = 12 // Проверка кода после значащего слова
}

/// <summary>Режим учёта падежей (рус.) и числа (англ.) для значащих слов.</summary>
public enum MorphologyMode { Off, Paradigms, Aggressive }

public static class RuleCatalog
{
    /// <summary>Порядок отображения — как в файле правил (1..12).</summary>
    public static readonly RuleId[] DisplayOrder =
    {
        RuleId.DecimalSeparator, RuleId.TrimSpaces, RuleId.ControlChars, RuleId.DimensionX,
        RuleId.ThreadDesignation, RuleId.Dashes, RuleId.SignificantWords,
        RuleId.TrailingEnding, RuleId.ArticleExclusion, RuleId.HomoglyphLetters,
        RuleId.ArticleExtraction, RuleId.CatalogStartReview
    };

    /// <summary>
    /// ОПТИМАЛЬНЫЙ порядок применения (отличается от порядка в ТЗ):
    /// 9 — ранний выход; 3 — снять невидимые символы, ломающие все шаблоны;
    /// 6 — нормализовать тире (границы слов); 2 — пробелы после NBSP;
    /// 5 перед 4 — частный случай раньше общего; 1 — последним из символьных;
    /// 7 и 8 — по нормализованной строке;
    /// 10 — САМЫМ ПОСЛЕДНИМ; 11 — после всех преобразований; 12 — классификатор ручной проверки.
    /// Для правила 12 начало значащего слова фиксируется до правила 7,
    /// а классификация выполняется по результату остальных преобразований.
    /// </summary>
    public static readonly RuleId[] ApplyOrder =
    {
        RuleId.ArticleExclusion, RuleId.ControlChars, RuleId.Dashes, RuleId.TrimSpaces,
        RuleId.ThreadDesignation, RuleId.DimensionX, RuleId.DecimalSeparator,
        RuleId.SignificantWords, RuleId.TrailingEnding, RuleId.HomoglyphLetters,
        RuleId.ArticleExtraction, RuleId.CatalogStartReview
    };

    /// <summary>Сокращённое обозначение правила — для GUI и Excel.</summary>
    public static string ShortName(RuleId id) => id switch
    {
        RuleId.DecimalSeparator => "Замена точки на запятую",
        RuleId.TrimSpaces => "Удаление лишних пробелов",
        RuleId.ControlChars => "Удаление служебных символов",
        RuleId.DimensionX => "Замена «х» в размерах",
        RuleId.ThreadDesignation => "Замена символов в резьбе",
        RuleId.Dashes => "Замена тире на минус",
        RuleId.SignificantWords => "Удаление значащих слов",
        RuleId.TrailingEnding => "Удаление окончания",
        RuleId.ArticleExclusion => "Комм. код удалён по виду артикула",
        RuleId.HomoglyphLetters => "Замена кирилл. А на англ. A и подобных",
        RuleId.ArticleExtraction => "Оставить код, совпадающий с артикулом",
        RuleId.CatalogStartReview => "Проверка кода после значащего слова",
        _ => id.ToString()
    };

    /// <summary>Текст для столбца «Критерий изменений».</summary>
    public static string CriteriaName(RuleId id) =>
        id == RuleId.ArticleExclusion
            ? "Комм. код удалён, номенклатура не для продажи"
            : ShortName(id);

    public static IEnumerable<RuleId> All => DisplayOrder;

    /// <summary>Жёстко связанные правила: 7 и 8 включаются/выключаются только вместе.</summary>
    public static IReadOnlyList<RuleId[]> LinkedGroups { get; } = new[]
    {
        new[] { RuleId.SignificantWords, RuleId.TrailingEnding }
    };

    /// <summary>Резервный текст правил для блока «в» вкладки настроек анализа.</summary>
    public const string FallbackRulesText = """
        Правила применяются последовательно к значению из столбца «Коммерческий код».

        1. Замена «.» на «,» в размерах и единицах измерения
           Точка -> запятая: в обозначении резьбы; после числа перед единицей измерения
           (mm, мм, кОм и подобные); в перечислении размеров (10х1.5, 2x2x0.5).
           Значения вида 28.58.49 остаются без изменений.
           M18х1.5 -> M18х1,5 | Резистор 1.5 кОм -> Резистор 1,5 кОм

        2. Удаление пробелов в начале и в конце значения
           ␣␣SE32-16␣␣ -> SE32-16

        3. Удаление непечатаемых и служебных символов
           Табуляция, неразрывный/нулевой пробел, символы управления.
           SE32<TAB>16 -> SE3216

        4. Замена «х» или «x» на латинскую «x» в перечислениях размеров
           20х20х3 -> 20x20x3 | 27х3.48 -> 27x3,48

        5. Замена «х»/«x» на «X» и «М»/«m» на «M» в обозначениях резьбы
           М12х1,5 -> M12X1,5 | m12x1.5 -> M12X1,5

        6. Замена en dash и em dash на минус
           BW300D1–KIT -> BW300D1-KIT

        7. Удаление значащих слов
           Слово удаляется только если ограничено пробелом или границей строки
           (защита конструкций Air/Water и суффиксов -KIT).
           V474LM70 Butterfly valve -> V474LM70

        8. Удаление окончания
           Если после удаления значащих слов значение оканчивается на одно из
           значений списка окончаний (в т.ч. неявных: DN**, Ду***), оно удаляется.
           Окончание удаляется только если оно было окончанием значения ДО
           удаления значащих слов.
           40M2C160B3500-UA01 Cylinders series 40 -> 40M2C160B3500-UA01

        9. Комм. код удалён по виду артикула
           Если артикул начинается с префикса, оканчивается на суффикс или содержит
           подстроку из «Артикулы_исключения.xlsx» — комм. код удаляется полностью.
           SRF76-1234 -> (комм. код удалён)

        10. Замена кириллических букв, совпадающих по написанию с латинскими
           Кириллические буквы А, В, Е, К, М, Н, О, Р, С, Т, Х, У заменяются на
           одинаковые по написанию латинские A, B, E, K, M, H, O, P, C, T, X, Y.

           Замена выполняется ТОЛЬКО если после применения всех остальных правил
           в значении не осталось ДРУГИХ кириллических букв. Наличие хотя бы одной
           кириллической буквы, не входящей в список замен, отменяет замену для
           всего значения целиком.

           Список замен подгружается из внешнего файла «Замены символов.xlsx» при
           запуске программы. Формат файла: один лист, два столбца с заголовками
           в первой строке — «Заменяемый символ» и «Корректный символ»; со второй
           строки по одной паре символов в строке. Регистр учитывается: чтобы
           обрабатывались строчные буквы, добавьте их в файл отдельными строками.

           Примеры:
           РС-100А          -> PC-100A
           Заслонка РС-100А -> PC-100A   (после удаления значащего слова)
           МАХ-12Т          -> MAX-12T
           ПЗК-RU52         -> ПЗК-RU52  (замены нет: буква «П» не в списке)
           БУ-04-РФ03      -> БУ-04-РФ03 (замены нет: буквы «Б» и «Ф» не в списке)

        11. Оставить в коммерческом коде артикул
           Если коммерческий код содержит артикул отдельной последовательностью,
           удаляются остальные символы. Например:
           Кольцо SRF50-25267-0015 25x68 -> SRF50-25267-0015.
           Правило выполняется после правила 9; при удалении кода по правилу 9
           результат остаётся пустым.

        12. Проверка кода после значащего слова
           Сначала проверяется исходное значение: начиналось ли оно со значащего
           слова. Эта проверка выполняется ДО правила 7, удаляющего значащие слова.
           Затем, с учётом результата применения остальных правил, строка
           направляется в файл «Коды для ручной проверки»:
           • потенциальный каталожный или модельный код сохраняется в столбце
             «Коммерческий код (исправленный)»;
           • если остались только размер, резьба, стандарт, материал, покрытие,
             технические параметры или код после предлога «для», «от», «for»,
             «of», «per» и подобных — исправленное значение оставляется пустым.
        """;
}